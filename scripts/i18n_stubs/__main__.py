"""Generate typed `Protocol`s for the translation strings of every extension."""

import argparse
import ast
import keyword
import re
import subprocess
import sys
from collections.abc import Iterator, Mapping, Sequence
from pathlib import Path

from src.i18n.classes import DEFAULT, CommandTranslation, ExtensionTranslation, RawTranslation, format_fields
from src.i18n.utils import YAML_SUFFIXES, find_translation_files, load_translation

EXTENSIONS = Path("src/extensions")
# Where stubs can live: next to an extension's own translations, or next to the centralized ones.
STUB_ROOTS = (EXTENSIONS, Path("src/translations"))
STUB_MARKER = "Generated by `pdm run i18n-stubs`"
STUB_DOCSTRING = STUB_MARKER + " from the translations next to it, do not edit."
# Reuse this file's license header, so that both stay in sync when the header is updated.
HEADER = "".join(Path(__file__).read_text(encoding="utf-8").splitlines(keepends=True)[:2])
# Typed `format` methods narrow `str.format`, which pyright reports as an incompatible override.
PYRIGHT_DIRECTIVE = "# pyright: reportIncompatibleMethodOverride=false\n"


def _identifier(name: str) -> str:
    """Ensure a name can be used as a Python identifier, as ``ast.unparse`` does not check it.

    Args:
        name: The name to check.

    Returns:
        The name.

    Raises:
        ValueError: If the name is not a valid identifier.

    """
    if not name.isidentifier() or keyword.iskeyword(name):
        raise ValueError(f"{name!r} is not a valid Python identifier")
    return name


def _pascal(name: str) -> str:
    # Context menu commands can be named with spaces and punctuation, e.g. ``Extract text (OCR)``.
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[\W_]+", name))


def _arguments(*, positional: int = 0, named: Sequence[str] = ()) -> ast.arguments:
    """Build the arguments of a method.

    Args:
        positional: Number of positional-only arguments after ``self``, named ``arg0``, ``arg1``...
        named: Names of the keyword-only arguments, typed as ``object``.

    Returns:
        The arguments.

    """
    leading = [ast.arg("self"), *(ast.arg(f"arg{i}", ast.Name("object")) for i in range(positional))]
    return ast.arguments(
        posonlyargs=leading if positional else [],
        args=[] if positional else leading,
        kwonlyargs=[ast.arg(_identifier(name), ast.Name("object")) for name in named],
        kw_defaults=[None] * len(named),
        defaults=[],
    )


def _method(name: str, arguments: ast.arguments, returns: str, decorator: str) -> ast.FunctionDef:
    return ast.FunctionDef(
        name=_identifier(name),
        args=arguments,
        body=[ast.Expr(ast.Constant(...))],
        decorator_list=[ast.Name(decorator)],
        returns=ast.Name(returns),
        type_params=[],
    )


def _formattable(name: str, translation: RawTranslation) -> ast.ClassDef | None:
    """Build a ``str`` subclass whose ``format`` method only accepts the string's arguments.

    Args:
        name: Name of the class.
        translation: The string, whose default text gives the arguments.

    Returns:
        The class definition, None if the string takes no arguments.

    """
    fields = format_fields(translation.root[DEFAULT])
    if not fields:
        return None
    return ast.ClassDef(
        name=_identifier(name),
        bases=[ast.Name("str")],
        keywords=[],
        body=[
            ast.Assign([ast.Name("__slots__")], ast.Tuple([])),
            _method("format", _arguments(positional=fields.positional, named=fields.named), "str", "override"),
        ],
        decorator_list=[ast.Name("final")],
        type_params=[],
    )


def _protocol(name: str, strings: Mapping[str, RawTranslation]) -> Iterator[ast.ClassDef]:
    """Build a protocol exposing each string as a property, preceded by the types of formattable strings.

    Args:
        name: Name of the protocol, ending with ``Strings``.
        strings: The strings to expose.

    Yields:
        The formattable strings' class definitions, then the protocol's.

    """
    properties: list[ast.stmt] = []
    for key, translation in strings.items():
        formattable = _formattable(name.removesuffix("Strings") + _pascal(key), translation)
        if formattable:
            yield formattable
        properties.append(_method(key, _arguments(), formattable.name if formattable else "str", "property"))
    yield ast.ClassDef(
        name=_identifier(name),
        bases=[ast.Name("Protocol")],
        keywords=[],
        body=properties,
        decorator_list=[],
        type_params=[],
    )


type KeyPath = tuple[str, ...]


def _command_protocols(
    commands: Mapping[str, CommandTranslation] | None, prefix: str = "", keys: KeyPath = ("commands",)
) -> Iterator[tuple[KeyPath, ast.ClassDef]]:
    """Build a protocol for the strings of each command and subcommand.

    Args:
        commands: The commands to build protocols for, keyed by name.
        prefix: Pascal case path of the parent command group.
        keys: Key path of ``commands`` in the translation.

    Yields:
        The key path of each command's strings, with the class definitions built from them.

    """
    for name, command in (commands or {}).items():
        path = prefix + _pascal(name)
        if command.strings:
            for cls in _protocol(f"{path}CommandStrings", command.strings):
                yield (*keys, name, "strings"), cls
        yield from _command_protocols(getattr(command, "commands", None), path, (*keys, name, "commands"))


def _classes(translation: ExtensionTranslation) -> list[tuple[KeyPath, ast.ClassDef]]:
    """Build every class of a translation, keyed by the path of the strings they come from.

    Args:
        translation: The extension's translation.

    Returns:
        The key paths and class definitions.

    Raises:
        ValueError: If several strings would generate classes of the same name.

    """
    classes: list[tuple[KeyPath, ast.ClassDef]] = []
    if translation.strings:
        classes += [(("strings",), cls) for cls in _protocol("ExtensionStrings", translation.strings)]
    classes += _command_protocols(translation.commands)
    names = [cls.name for _, cls in classes]
    if duplicates := sorted({name for name in names if names.count(name) > 1}):
        raise ValueError(f"Several strings would generate the classes {', '.join(duplicates)}")
    return classes


def _module(classes: Sequence[ast.ClassDef], target: Path) -> str:
    """Render a stub module, formatted with Ruff.

    Args:
        classes: The class definitions of the module, none for a package that only holds other stubs.
        target: Path of the module, which Ruff's configuration is resolved for.

    Returns:
        The module's source code.

    """
    formattable = any(base.id == "str" for cls in classes for base in cls.bases if isinstance(base, ast.Name))
    typing = [ast.alias("Protocol"), *([ast.alias("final"), ast.alias("override")] if formattable else [])]
    module = ast.Module(
        body=[
            ast.Expr(ast.Constant(STUB_DOCSTRING)),
            *([ast.ImportFrom("typing", typing, 0)] if classes else []),
            *classes,
        ],
        type_ignores=[],
    )
    header = HEADER + (PYRIGHT_DIRECTIVE if formattable else "")
    source = header + "\n" + ast.unparse(ast.fix_missing_locations(module))
    return subprocess.run(  # noqa: S603
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(target), "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def render(translation: ExtensionTranslation, target: Path = Path("translations.py")) -> str | None:
    """Render every class of a translation as one stub module, as for a single translation file.

    Args:
        translation: The extension's translation.
        target: Path of the module, which Ruff's configuration is resolved for.

    Returns:
        The module's source code, None if the translation has no strings.

    """
    classes = [cls for _, cls in _classes(translation)]
    return _module(classes, target) if classes else None


def _nodes(source: Path, keys: KeyPath = ()) -> Iterator[tuple[KeyPath, Path]]:
    """Map each file and folder of a translation to its Python module, the stub of the strings it holds.

    A file's module is next to it (``ping.yml`` to ``ping.py``), and a folder's is its package
    (``commands/`` to ``commands/__init__.py``), so a stub is imported like its translation is laid out.

    Args:
        source: A translation file or folder.
        keys: Key path of ``source`` in the translation.

    Yields:
        The key path of each file and folder, with its module.

    """
    if source.is_file():
        yield keys, source.with_suffix(".py")
        return
    yield keys, source / "__init__.py"
    for child in sorted(source.iterdir()):
        if child.is_dir() or child.suffix in YAML_SUFFIXES:
            yield from _nodes(child, (*keys, child.stem))


def stubs(source: Path) -> dict[Path, str]:
    """Render the stub modules of a translation, each class in the module of the deepest file or folder holding it.

    The packages of the folders leading to a stub are rendered too, so that every stub is in a regular package.

    Args:
        source: The translation file or folder.

    Returns:
        The source code of each stub module, keyed by its resolved path.

    """
    nodes = list(_nodes(source.resolve()))
    grouped: dict[Path, list[ast.ClassDef]] = {}
    for keys, cls in _classes(load_translation(source)):
        _, target = max((node for node in nodes if keys[: len(node[0])] == node[0]), key=lambda node: len(node[0]))
        grouped.setdefault(target, []).append(cls)
    for target in list(grouped):
        for _, module in nodes:
            if module.name == "__init__.py" and module.parent in target.parents:
                grouped.setdefault(module, [])
    return {target: _module(classes, target) for target, classes in grouped.items()}


def _is_stub(path: Path) -> bool:
    docstring = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")))
    return docstring is not None and docstring.startswith(STUB_MARKER)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate typed protocols for extension translation strings.")
    parser.add_argument("--check", action="store_true", help="Only check that the stubs are up to date")
    args = parser.parse_args()

    expected: dict[Path, str] = {}
    for extension in sorted(EXTENSIONS.iterdir()):
        # Only the first layer defines the strings, so that a bot overriding them does not change the stubs.
        if layers := find_translation_files(extension, extension.name):
            expected |= stubs(layers[0])
    outdated = sorted(
        path for path, content in expected.items() if not path.exists() or path.read_text(encoding="utf-8") != content
    )
    stale = sorted(
        path
        for root in STUB_ROOTS
        if root.exists()
        for path in root.resolve().rglob("*.py")
        if path not in expected and _is_stub(path)
    )

    for path in outdated:
        print(f"{'Outdated' if args.check else 'Wrote'} {path.relative_to(Path.cwd())}")
        if not args.check:
            path.write_text(expected[path], encoding="utf-8")
    for path in stale:
        print(f"{'Stale' if args.check else 'Removed'} {path.relative_to(Path.cwd())}")
        if not args.check:
            path.unlink()
    if args.check and (outdated or stale):
        print("Run `pdm run i18n-stubs` to update the translation stubs.")
        sys.exit(1)


if __name__ == "__main__":
    main()
