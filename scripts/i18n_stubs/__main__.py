"""Generate typed `Protocol`s for the translation strings of every extension."""

import argparse
import ast
import keyword
import re
import subprocess
import sys
from collections.abc import Iterator, Mapping
from pathlib import Path

from src.i18n.classes import CommandTranslation, ExtensionTranslation, RawTranslation
from src.i18n.utils import find_translation_file, load_translation

EXTENSIONS = Path("src/extensions")
STUB_NAME = "translation_types.py"
STUB_DOCSTRING = "Generated by `pdm run i18n-stubs` from this extension's translations, do not edit."
# Reuse this file's license header, so that both stay in sync when the header is updated.
HEADER = "".join(Path(__file__).read_text(encoding="utf-8").splitlines(keepends=True)[:2])


def _identifier(name: str) -> str:
    """Ensure a name can be used as a Python identifier, as ``ast.unparse`` does not check it.

    Args:
        name: The name to check.

    Returns:
        The name.

    Raises:
        ValueError: If the name is not a valid identifier.

    """
    if not name.isidentifier() or keyword.iskeyword(name):
        raise ValueError(f"{name!r} is not a valid Python identifier")
    return name


def _pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[-_]", name))


def _protocol(name: str, strings: Mapping[str, RawTranslation]) -> ast.ClassDef:
    """Build a protocol exposing each string as a ``str`` property.

    Args:
        name: Name of the protocol.
        strings: The strings to expose.

    Returns:
        The protocol's class definition.

    """
    properties: list[ast.stmt] = [
        ast.FunctionDef(
            name=_identifier(key),
            args=ast.arguments(posonlyargs=[], args=[ast.arg("self")], kwonlyargs=[], kw_defaults=[], defaults=[]),
            body=[ast.Expr(ast.Constant(...))],
            decorator_list=[ast.Name("property")],
            returns=ast.Name("str"),
            type_params=[],
        )
        for key in strings
    ]
    return ast.ClassDef(
        name=_identifier(name),
        bases=[ast.Name("Protocol")],
        keywords=[],
        body=properties,
        decorator_list=[],
        type_params=[],
    )


def _command_protocols(commands: Mapping[str, CommandTranslation] | None, prefix: str = "") -> Iterator[ast.ClassDef]:
    """Build a protocol for the strings of each command and subcommand.

    Args:
        commands: The commands to build protocols for, keyed by name.
        prefix: Pascal case path of the parent command group.

    Yields:
        The protocols' class definitions.

    """
    for name, command in (commands or {}).items():
        path = prefix + _pascal(name)
        if command.strings:
            yield _protocol(f"{path}CommandStrings", command.strings)
        yield from _command_protocols(getattr(command, "commands", None), path)


def render(translation: ExtensionTranslation) -> str | None:
    """Render the stub module of an extension's translation, formatted with Ruff.

    Args:
        translation: The extension's translation.

    Returns:
        The module's source code, None if the translation has no strings.

    """
    protocols = list(_command_protocols(translation.commands))
    if translation.strings:
        protocols.insert(0, _protocol("ExtensionStrings", translation.strings))
    if not protocols:
        return None
    module = ast.Module(
        body=[
            ast.Expr(
                ast.Constant("Generated by `pdm run i18n-stubs` from this extension's translations, do not edit.")
            ),
            ast.ImportFrom("typing", [ast.alias("Protocol")], 0),
            *protocols,
        ],
        type_ignores=[],
    )
    source = HEADER + "\n" + ast.unparse(ast.fix_missing_locations(module))
    return subprocess.run(  # noqa: S603
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", STUB_NAME, "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate typed protocols for extension translation strings.")
    parser.add_argument("--check", action="store_true", help="Only check that the stubs are up to date")
    args = parser.parse_args()

    outdated: list[Path] = []
    for extension in sorted(EXTENSIONS.iterdir()):
        source = find_translation_file(extension, extension.name)
        content = render(load_translation(source)) if source else None
        target = extension / STUB_NAME
        if content is None or (target.exists() and target.read_text(encoding="utf-8") == content):
            continue
        outdated.append(target)
        if not args.check:
            target.write_text(content, encoding="utf-8")

    for target in outdated:
        print(f"{'Outdated' if args.check else 'Wrote'} {target}")
    if args.check and outdated:
        print("Run `pdm run i18n-stubs` to update the translation stubs.")
        sys.exit(1)


if __name__ == "__main__":
    main()
